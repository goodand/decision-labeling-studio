"""Unattended learning cycle: learn_now -> eval_loop -> publish.

Runs per project only when MIN_NEW new observations exist since the last run (throttle).
- status active  (rules pass + 3/3 judge accept) -> appended to HABITS (agent-habit memory, 메타)
- status candidate/manual_review                -> listed in DIGEST for the user to skim
Nothing here edits project rules or domain memory (실사용 lessons stay human-written).
Usage: python auto_learn.py [--force] [project ...]
"""
import json, os, sys, time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import learn_now, eval_loop  # noqa: E402  (reuse, no new logic)

STORE = learn_now.STORE
_MEM = Path.home() / ".claude" / "projects"  # Claude Code auto-memory root; set the env per machine


def _out(env: str, legacy: Path, name: str) -> Path:
    """env > the original Windows machine's memory file (only where it exists) > the store."""
    if os.environ.get(env):
        return Path(os.environ[env])
    return legacy if legacy.parent.exists() else STORE / name


DIGEST = _out("ECC_LEARN_DIGEST", _MEM / "D--dev-eval-team" / "memory" / "learned-digest.md", "learned-digest.md")
HABITS = _out("ECC_LEARN_HABITS", _MEM / "C--Users-INTEC" / "memory" / "learned-agent-habits.md", "learned-agent-habits.md")
MIN_NEW = 20
FAIL_COOLDOWN_S = 6 * 3600  # after a failed learn (e.g. claude -p refused), don't respawn it on every Stop
MAX_HABITS = 15


def _count(pdir: Path) -> int:
    """Lines across observations.jsonl, its observe.sh archive (rotation at 10MB) and corrections.jsonl,
    so the delta since the last run is monotonic and corrections alone can trigger a run."""
    files = sorted((pdir / "observations.archive").glob("*.jsonl")) + [pdir / "observations.jsonl", pdir / "corrections.jsonl"]
    return sum(1 for f in files if f.exists() for l in f.read_text("utf-8").splitlines() if l.strip())


def due(pdir: Path) -> bool:
    marker = pdir / ".auto_learn.json"
    last = json.loads(marker.read_text("utf-8")).get("count", 0) if marker.exists() else 0
    return _count(pdir) - last >= MIN_NEW


def cooling_down(pdir: Path) -> bool:
    err = pdir / ".auto_learn_error.json"
    return err.exists() and time.time() - json.loads(err.read_text("utf-8")).get("epoch", 0) < FAIL_COOLDOWN_S


def mark_done(pdir: Path):
    (pdir / ".auto_learn.json").write_text(json.dumps({"count": _count(pdir), "at": time.strftime("%Y-%m-%dT%H:%M:%S")}), "utf-8")


def _action(md: Path) -> str:
    body = md.read_text("utf-8")
    m = body.split("## Action", 1)
    return m[1].split("##", 1)[0].strip() if len(m) == 2 else ""


def publish(results: dict, registry: dict):
    by_name = {v["name"]: k for k, v in registry.items()}
    head = ("---\nname: learned-agent-habits\ndescription: Auto-promoted 메타 habits from ECC instincts "
            "(rules pass + 3/3 judge accept); generated by auto_learn.py, do not hand-edit\nmetadata:\n  type: feedback\n---\n\n")
    existing = HABITS.read_text("utf-8") if HABITS.exists() else head
    digest = [f"# Learned digest ({time.strftime('%Y-%m-%d %H:%M')})", ""]
    for name, rs in results.items():
        for r in rs:
            md = STORE / "projects" / by_name[name] / "instincts" / "personal" / r["file"]
            key = f"<!-- {name}/{r['file']} -->"
            if r["status"] == "active" and key not in existing and md.exists():
                existing += f"- {_action(md)} {key}\n"
            elif r["status"] != "active":
                digest.append(f"- {name} | {r['file']} | {r['status']} | judge={(r.get('semantic') or {}).get('verdicts')}")
    lines = existing.splitlines()
    body = [l for l in lines if l.startswith("- ")][-MAX_HABITS:]
    HABITS.parent.mkdir(parents=True, exist_ok=True)
    HABITS.write_text("\n".join([l for l in lines if not l.startswith("- ")] + body) + "\n", "utf-8")
    DIGEST.parent.mkdir(parents=True, exist_ok=True)
    old = DIGEST.read_text("utf-8").splitlines() if DIGEST.exists() else []
    kept = [l for l in old if l.startswith("- ")]                      # unread candidates from earlier runs
    new = [l for l in digest if l.startswith("- ") and l not in kept]
    DIGEST.write_text("\n".join([digest[0], ""] + kept + new) + "\n", "utf-8")


def main(argv):
    force = "--force" in argv
    names = [a for a in argv if not a.startswith("--")]
    reg_file = STORE / "projects.json"  # written by ECC observe.sh once a git project is seen
    if not reg_file.exists():
        print("nothing due (no projects registered yet)")
        return
    registry = json.loads(reg_file.read_text("utf-8"))
    results = {}
    for pid, meta in registry.items():
        pdir = STORE / "projects" / pid
        if names and meta["name"] not in names or not (force or (due(pdir) and not cooling_down(pdir))):
            continue
        learned = learn_now.run(pdir, meta)
        print(meta["name"], "learn ->", learned, flush=True)
        if not learned.startswith("ok"):  # refused/incomplete/leak/skip: the data was not learned, keep it due
            (pdir / ".auto_learn_error.json").write_text(json.dumps(
                {"result": learned[:300], "epoch": time.time(), "at": time.strftime("%Y-%m-%dT%H:%M:%S")}), "utf-8")
            continue
        (pdir / ".auto_learn_error.json").unlink(missing_ok=True)
        # Rules + human review by default; the LLM judge stage is opt-in (user rule 2026-10-23:
        # LLM judging was neither more accurate nor reproducible — imitate human patterns as rules).
        results[meta["name"]] = eval_loop.evaluate_project(pdir, meta, os.environ.get("ECC_LEARN_SEMANTIC") == "1")
        mark_done(pdir)
    if results:
        publish(results, registry)
        print("published:", HABITS, DIGEST)
    else:
        print("nothing due")


if __name__ == "__main__":
    main(sys.argv[1:])
